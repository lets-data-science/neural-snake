"""Run 1: unattended 60-minute training of R1v2 + ate head (Net3, dilated, MPS, fp32, channels_last) on old + new train rows.
Validation = the Spike A validation split (seed % 5 == 1, same 10,374 rows as v3, so numbers compare). Held-out rows are never loaded.
New-seed validation rows are generated by gen_run1.py but left unused.

  .venv/bin/python spikes/spike_a/run1.py train [seconds]      (default 3600)
  .venv/bin/python spikes/spike_a/run1.py eval <checkpoint>    (re-run only the final evaluation)
"""
import json
import math
import os
import sys
import time

import numpy as np
import torch

HERE = os.path.dirname(__file__)
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, HERE)
import common  # noqa: E402
import v2  # noqa: E402
import v3  # noqa: E402

DEV = torch.device("mps")
CKPT_DIR = os.path.join(ROOT, "checkpoints")
CKPT_EVERY_S, LOG_EVERY_S = 600.0, 300.0
ROLLOUT_CAP, ROLLOUTS_PER_KIND = 200, 100


def load_all():
    tr_old, va = common.load_trainval()
    common.DATA = os.path.join(ROOT, "data", "run1")
    tr_new, _va_new_unused = common.load_trainval()
    common.DATA = os.path.join(ROOT, "data", "spike_a")
    tr = {k: np.concatenate([tr_old[k], tr_new[k]]) for k in tr_old}
    return tr, va, len(tr_old["act"]), len(tr_new["act"])


def new_net():
    return v3.Net3("dil", ate=True).to(DEV).to(memory_format=torch.channels_last)


def subset_acc(net, Ts, y14s, eat):
    P = v3.predict(net, Ts, len(eat))
    ok = (P["cls"].numpy() == y14s).reshape(len(eat), -1).all(1)
    return {"overall": round(float(ok.mean()), 4), "eat": round(float(ok[eat].mean()), 4), "non_eat": round(float(ok[~eat].mean()), 4)}


def save_ckpt(net, tag, extra):
    os.makedirs(CKPT_DIR, exist_ok=True)
    path = os.path.join(CKPT_DIR, f"run1_{tag}.pt")
    torch.save({"state_dict": net.state_dict(), **extra}, path)
    return path


def evaluate(net, va, Tv, x14v, y14v, train_info, tag="run1"):
    v2.DEV, v2.HORIZON = DEV, ROLLOUT_CAP
    res = dict(train_info)
    res["val"] = v3.eval_val(net, va, Tv, x14v, y14v)
    res["rollout_cap_steps"] = ROLLOUT_CAP
    t = time.time()
    res["rollout_bfs"], f1 = v2.rollouts("R1v2", net, va, x14v, "bfs", n=ROLLOUTS_PER_KIND, seed=1)
    res["rollout_random_safe"], f2 = v2.rollouts("R1v2", net, va, x14v, "random", n=ROLLOUTS_PER_KIND, seed=2)
    res["rollout_seconds"] = round(time.time() - t, 1)
    for r in (res["rollout_bfs"], res["rollout_random_safe"]):
        r["note"] = f"{ROLLOUT_CAP + 1} = censored (no event within the {ROLLOUT_CAP}-step cap)"
    ex = res["val"]["exact"]
    res["implied_median_from_p"] = {}
    for name, p in (("overall_exact", ex["all"]["all_steps"]["model_exact"]), ("non_eat_exact", ex["all"]["non_eat_steps"]["model_exact"]),
                    ("bucket_balanced_exact", float(np.mean([ex[b]["all_steps"]["model_exact"] for b, *_ in v2.BUCKETS])))):
        res["implied_median_from_p"][name] = {"p": round(p, 4), "median_steps": round(math.log(0.5) / math.log(p), 2) if 0 < p < 1 else None}
    fails = f1[:1] + f2[:1]
    write_md(res, fails, tag)
    json.dump(res, open(os.path.join(HERE, f"results_{tag}.json"), "w"), indent=1)
    print(json.dumps({k: v for k, v in res.items() if k != "val"}, indent=1), flush=True)


def write_md(r, fails, tag="run1"):
    v = r["val"]
    L = [f"# {tag} results (VALIDATION, seed % 5 == 1, Spike A rows)", "", f"Command: `{r.get('command')}`; raw numbers in `results_{tag}.json`.", "",
         f"Train rows {r.get('n_train')}, steps {r.get('steps')}, {r.get('seconds')} s, {r.get('samples_per_s')} samples/s.", "",
         "## Whole-board exact match by snake length (model / copy-previous-frame baseline)", "",
         "| length | all steps | eat steps | non-eat steps |", "|---|---|---|---|"]
    for b, row in v["exact"].items():
        L.append(f"| {b} | " + " | ".join(f"{row[s]['model_exact']} / {row[s]['copy14']} (n={row[s]['n']})" for s in ("all_steps", "eat_steps", "non_eat_steps")) + " |")
    L += ["", "## Per-class cell error (%, 14-class; type-only; eat / non-eat steps)", "", "| class | cells | wrong | type-only | eat | non-eat |", "|---|---|---|---|---|---|"]
    for k, e in v["per_cell_error"].items():
        L.append(f"| {k} | {e['cells']} | {e['pct_wrong_14class']} | {e['pct_wrong_type_only']} | {e['pct_wrong_14class_eat_steps']} | {e['pct_wrong_14class_non_eat_steps']} |")
    L += ["", f"Game over: {v['game_over']}", "", f"Ate head: {v.get('ate_head')}", "",
          f"Food spawn on empty cell: {v['food_spawn_on_empty_pct']}% over {v['n_eat_steps']} eat steps", "",
          f"## Rollouts (cap {r['rollout_cap_steps']}, food synced)", ""]
    for k in ("rollout_bfs", "rollout_random_safe"):
        x = r[k]
        L.append(f"- {x['kind']} n={x['n']}: first mismatch median {x['first_mismatch_median']}, p10 {x['first_mismatch_p10']}, "
                 f"matched to end {x['matched_to_end']}, no mismatch within cap {x['no_mismatch_within_20']}, first invalid median {x['first_invalid_median']}, "
                 f"invalid reasons {x['invalid_reasons']}")
    L += ["", "Implied median ln(0.5)/ln(p): " + json.dumps(r["implied_median_from_p"]), "", "## Failure grids", ""]
    for x in fails:
        L += [f"{x['kind']} rollout {x['rollout']} step {x['step']} action {x['action']}", "```", x["ascii"], "```", ""]
    open(os.path.join(HERE, f"results_{tag}.md"), "w").write("\n".join(L))


def main_train(seconds):
    assert torch.backends.mps.is_available()
    t_load = time.time()
    tr, va, n_old, n_new = load_all()
    print(f"loaded train old={n_old} new={n_new} total={len(tr['act'])} val={len(va['act'])} ({time.time()-t_load:.0f}s)", flush=True)
    x14t, y14t = common.make_14(tr)
    x14v, y14v = common.make_14(va)
    print(f"made 14-class grids ({time.time()-t_load:.0f}s)", flush=True)
    Tt, Tv = v3.make_device_data(tr, x14t, y14t, DEV), v3.make_device_data(va, x14v, y14v, DEV)
    sub = np.sort(np.random.default_rng(0).choice(len(va["act"]), 2000, replace=False))
    vs = {k: v[sub] for k, v in va.items()}
    Ts, y14s, eat_s = v3.make_device_data(vs, x14v[sub], y14v[sub], DEV), y14v[sub], vs["eaten"].astype(bool)
    torch.manual_seed(0)
    S = v3.Sampler(tr, DEV, 256)
    net = new_net()
    shifts = v3.prior_shifts(net, S, Tt, tr, DEV)
    curve, state = [], {"next_ckpt": CKPT_EVERY_S}

    def cb(step, t, loss):
        a = subset_acc(net, Ts, y14s, eat_s)
        curve.append({"t_s": round(t), "step": step, "loss": round(loss, 4), "val2000": a})
        print(f"t={t:.0f}s step={step} loss={loss:.4f} samples/s={step*256/t:.0f} val2000={a}", flush=True)
        if t >= state["next_ckpt"]:
            print("checkpoint", save_ckpt(net, f"{int(t // 60)}min", {"step": step, "t_s": t}), flush=True)
            state["next_ckpt"] += CKPT_EVERY_S
        return False
    step, el, loss = v3.run_training(net, Tt, S, seconds, DEV, 1e-4, log_every_s=LOG_EVERY_S, eval_cb=cb)
    print("final checkpoint", save_ckpt(net, "final", {"step": step, "t_s": el}), flush=True)
    info = {"command": f"run1.py train {seconds}", "n_train": int(len(tr["act"])), "n_train_old": n_old, "n_train_new": n_new,
            "n_val": int(len(va["act"])), "steps": step, "seconds": round(el, 1), "samples_per_s": round(step * 256 / el),
            "final_loss": round(loss, 4), "prior_shifts": shifts, "val2000_curve": curve}
    evaluate(net, va, Tv, x14v, y14v, info)


def main_eval(path):
    _, va = common.load_trainval()
    x14v, y14v = common.make_14(va)
    Tv = v3.make_device_data(va, x14v, y14v, DEV)
    net = new_net()
    net.load_state_dict(torch.load(path)["state_dict"])
    evaluate(net, va, Tv, x14v, y14v, {"command": f"run1.py eval {path}", "n_val": int(len(va["act"]))})


if __name__ == "__main__":
    if sys.argv[1] == "train":
        main_train(float(sys.argv[2]) if len(sys.argv) > 2 else 3600.0)
    else:
        main_eval(sys.argv[2])
